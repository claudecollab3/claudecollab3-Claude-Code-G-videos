import React, { useState } from "react";
import { apiJson } from "../api";
import EquityCurveChart from "../components/EquityCurveChart";

interface PerformanceReport {
  total_trades: number;
  win_rate: number;
  profit_factor: number | null;
  sharpe_ratio: number | null;
  sortino_ratio: number | null;
  max_drawdown_percent: number;
  average_win: number;
  average_loss: number;
  expectancy: number;
}

interface BacktestTrade {
  strategy_name: string;
  symbol: string;
  direction: string;
  entry_time: string;
  entry_price: number;
  exit_time: string;
  exit_price: number;
  volume: number;
  pnl: number;
  r_multiple: number;
  exit_reason: string;
}

interface BacktestResponse {
  symbol: string;
  starting_balance: number;
  ending_balance: number;
  rejected_signal_count: number;
  performance: PerformanceReport;
  equity_curve: { timestamp: string; equity: number }[];
  trades: BacktestTrade[];
}

export default function BacktestPage() {
  const [symbol, setSymbol] = useState("EURUSD");
  const [startingBalance, setStartingBalance] = useState(10000);
  const [result, setResult] = useState<BacktestResponse | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function run(e: React.FormEvent) {
    e.preventDefault();
    setLoading(true);
    setError(null);
    try {
      const data = await apiJson<BacktestResponse>("/backtesting/run", {
        method: "POST",
        body: JSON.stringify({ symbol, starting_balance: startingBalance }),
      });
      setResult(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Backtest failed");
    } finally {
      setLoading(false);
    }
  }

  return (
    <div>
      <h2>Backtesting</h2>
      <p className="hint">
        Replays persisted OHLCV history through the same strategy engine and risk manager used live.
        Sync market data for a symbol in the Broker tab first.
      </p>
      <form className="inline-form" onSubmit={run}>
        <input value={symbol} onChange={(e) => setSymbol(e.target.value.toUpperCase())} placeholder="EURUSD" />
        <input
          type="number"
          value={startingBalance}
          onChange={(e) => setStartingBalance(Number(e.target.value))}
          min={1}
        />
        <button type="submit" className="btn-primary" disabled={loading}>
          {loading ? "Running..." : "Run backtest"}
        </button>
      </form>
      {error && <p className="error">{error}</p>}
      {result && (
        <>
          <div className="stat-row">
            <div>
              <span className="stat-label">Trades</span>
              <span className="stat-value">{result.performance.total_trades}</span>
            </div>
            <div>
              <span className="stat-label">Win rate</span>
              <span className="stat-value">{result.performance.win_rate.toFixed(1)}%</span>
            </div>
            <div>
              <span className="stat-label">Profit factor</span>
              <span className="stat-value">{result.performance.profit_factor?.toFixed(2) ?? "—"}</span>
            </div>
            <div>
              <span className="stat-label">Sharpe</span>
              <span className="stat-value">{result.performance.sharpe_ratio?.toFixed(2) ?? "—"}</span>
            </div>
            <div>
              <span className="stat-label">Max drawdown</span>
              <span className="stat-value">{result.performance.max_drawdown_percent.toFixed(1)}%</span>
            </div>
            <div>
              <span className="stat-label">Expectancy</span>
              <span className="stat-value">{result.performance.expectancy.toFixed(2)}</span>
            </div>
          </div>

          <h3>Equity Curve</h3>
          <EquityCurveChart points={result.equity_curve} />

          <h3>Trade Journal ({result.trades.length})</h3>
          {result.trades.length === 0 ? (
            <p className="hint">No trades were generated by this backtest.</p>
          ) : (
            <table className="data-table">
              <thead>
                <tr>
                  <th>Strategy</th>
                  <th>Dir</th>
                  <th>Entry</th>
                  <th>Exit</th>
                  <th>PnL</th>
                  <th>R</th>
                  <th>Reason</th>
                </tr>
              </thead>
              <tbody>
                {result.trades.map((t, i) => (
                  <tr key={i}>
                    <td>{t.strategy_name.replace(/_/g, " ")}</td>
                    <td>{t.direction}</td>
                    <td>{new Date(t.entry_time).toLocaleString()}</td>
                    <td>{new Date(t.exit_time).toLocaleString()}</td>
                    <td className={t.pnl >= 0 ? "positive" : "negative"}>{t.pnl.toFixed(2)}</td>
                    <td>{t.r_multiple.toFixed(2)}</td>
                    <td>{t.exit_reason.replace(/_/g, " ")}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </>
      )}
    </div>
  );
}
